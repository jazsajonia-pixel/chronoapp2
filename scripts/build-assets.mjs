/**
 * Generates bundled string assets the app embeds (Hermes can't read function source at runtime):
 *  - src/generated/editor-html.ts      CodeMirror 6 editor page for the editor WebView
 *  - src/generated/preview-runtime.ts  the preview iframe runtime (from src/features/preview/runtime.ts)
 * Run: npm run build:assets (also runs on postinstall).
 */
import { build } from "esbuild";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "src/generated");
mkdirSync(out, { recursive: true });

// 1) Editor
const editor = await build({
  entryPoints: [join(root, "editor/editor.ts")],
  bundle: true,
  write: false,
  format: "iife",
  minify: true,
  target: ["es2020"],
  legalComments: "none",
});
const css = readFileSync(join(root, "editor/vars.css"), "utf8");
const js = editor.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const html = `<!doctype html><html class="dark"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover"><style>${css}</style></head><body><div id="editor"></div><script>${js}</script></body></html>`;
writeFileSync(join(out, "editor-html.ts"), `// Generated by scripts/build-assets.mjs — do not edit.\nexport const EDITOR_HTML = ${JSON.stringify(html)};\n`);

// 2) Preview runtime: evaluate previewRuntime.toString() under Node (keeps real source text).
const { transform } = await import("esbuild");
const rtSrc = readFileSync(join(root, "src/features/preview/runtime.ts"), "utf8").replace(/^import .*$/gm, "");
const rt = await transform(rtSrc, { loader: "ts", format: "esm", target: "es2019" });
const tmp = join(out, ".runtime.mjs");
writeFileSync(tmp, "const PREVIEW_RUNTIME_SOURCE = '';\n" + rt.code + "\nexport const __src = previewRuntime.toString();\n");
const mod = await import(pathToFileURL(tmp).href + `?t=${Date.now()}`);
writeFileSync(join(out, "preview-runtime.ts"), `// Generated by scripts/build-assets.mjs — do not edit.\nexport const PREVIEW_RUNTIME_SOURCE = ${JSON.stringify(mod.__src)};\n`);
const { rmSync } = await import("node:fs");
rmSync(tmp);
console.log(`editor-html: ${(html.length / 1024).toFixed(0)} KB, preview-runtime: ${(mod.__src.length / 1024).toFixed(1)} KB`);
